import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { build } from 'astro';

const root = fileURLToPath(new URL('../', import.meta.url));
const routePath = 'src/pages/cgv.astro';
const copyPath = 'src/drafts/mc2-cgv-2026-09-v7.md';
const legacyPath = 'src/components/legal/LegacyTerms.astro';
const [route, copy, historical] = await Promise.all([
  fs.readFile(path.join(root, routePath), 'utf8'),
  fs.readFile(path.join(root, copyPath), 'utf8'),
  fs.readFile(path.join(root, legacyPath), 'utf8'),
]);

assert.equal((copy.match(/^## \d+\./gm) || []).length, 18);
for (const text of [
  'douze mois consécutifs', 'pas de treizième mensualité',
  'pas à un essai gratuit', 'Morpho pendant vingt-quatre mois',
  'les leçons 1 à 8 du module 3 incluses', 'au maximum trois nouvelles leçons',
  'Les révisions sont libres', 'vérification humaine', 'uniquement la Garantie Manifestation',
  '125 € par séance', '648,50 €', 'aucune facture complémentaire',
  'les échéances non encore encaissées sont annulées',
  'quatorze jours à compter de sa conclusion', '/confidentialite/',
]) assert.ok(copy.includes(text), `Missing term: ${text}`);

assert.ok(copy.includes(`${12 * 197}`.replace(/^(\d)(\d{3})$/, '$1 $2') + ' €'));
assert.ok(copy.includes(`${6 * 347}`.replace(/^(\d)(\d{3})$/, '$1 $2') + ' €'));
assert.ok(copy.includes(`${12 * 197 - 6 * 347} €`));
assert.ok(copy.includes(`${788 - 125} €`));
assert.equal(1297 / 2, 648.5);
assert.equal(Math.ceil((3 + 30 + 8) / 3), 14); // Illustrative M2 count, not an extra contract condition.
for (const [paid, coach, consultation] of [[0, 0, false], [197, 1, true], [788, 1, false], [1182, 3, true]]) {
  const deduction = Math.min(paid, coach * 125 + (consultation ? 648.5 : 0));
  const refund = paid - deduction;
  assert.ok(refund >= 0 && refund <= paid);
  assert.equal(refund + deduction, paid);
}

assert.ok(historical.includes('1 997 € TTC') && historical.includes('trois mensualités de 767 € TTC'));
assert.ok(historical.includes('douze (12) mois à compter de la date'));
assert.ok(!historical.includes('trois nouvelles leçons'));
assert.ok(route.includes('noindex, nofollow, noarchive'));
assert.ok(!route.includes('GAConsentMode') && !route.includes('Spiffy'));

assert.ok(!route.includes('import.meta.env.DEV'), 'Approved CGV must be included in the build');
assert.ok(!copy.includes('v7-projet'));
assert.ok(route.includes('Les contrats déjà conclus restent inchangés'));
assert.ok(route.includes('autres-offres-et-anciennes-formules') && route.includes('<LegacyTerms />'));
assert.ok(copy.includes('articles 1 à 18') && copy.includes('article 19'));
assert.ok(!route.includes('/mc2/draftx/cgv/'));
assert.ok(!await fs.stat(path.join(root, 'src/pages/mc2/draftx/cgv.astro')).catch(() => null));
const redirects = await fs.readFile(path.join(root, 'public/_redirects'), 'utf8');
assert.match(redirects, /\/mc2\/draftx\/cgv\/\s+\/cgv\/\s+301!/);

// Compile the actual page + Markdown in an isolated temporary Astro site.
// No deployment, existing build output, payment, external API or browser automation.
// macOS aliases /var to /private/var; Astro's virtual CSS ids need one canonical root.
const fixture = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'mc2-cgv-build-check-')));
for (const relative of [routePath, copyPath, legacyPath]) {
  await fs.mkdir(path.dirname(path.join(fixture, relative)), { recursive: true });
  await fs.copyFile(path.join(root, relative), path.join(fixture, relative));
}
await fs.symlink(path.join(root, 'node_modules'), path.join(fixture, 'node_modules'), 'dir');
await build({ root: fixture, configFile: false, logLevel: 'error', telemetry: false });
const outputFiles = await fs.readdir(path.join(fixture, 'dist'), { recursive: true }).catch(() => []);
assert.ok(outputFiles.includes('cgv/index.html'), 'Approved CGV must be generated by a production build');
const html = await fs.readFile(path.join(fixture, 'dist/cgv/index.html'), 'utf8');
assert.ok(html.includes('cgv-2026-09-v8') && html.includes('648,50'));
assert.ok(html.includes('1 997 € TTC') && html.includes('trois mensualités de 767 € TTC'));
console.log('CGV checks passed: 18 articles, pricing, guarantee, legacy terms preserved, canonical /cgv/ route.');
console.log(`Isolated production build: CGV page generated. Temporary output: ${fixture}`);
