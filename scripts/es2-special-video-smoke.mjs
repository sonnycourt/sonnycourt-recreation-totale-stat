import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { initSpecialVideo } from '../src/lib/es2-special-video.mjs';
import { bunnyEmbedUrl } from '../src/lib/es2-special-offer.mjs';
import { specialOffer } from '../src/data/es2-offre-speciale.mjs';
const initial = bunnyEmbedUrl(specialOffer);
let navigations = 0, current = initial;
const frame = { get src() { return current; }, set src(value) { navigations++; current = value; } };
const handlers = [];
const poster = { hidden: true, addEventListener: (event, callback) => { assert.equal(event, 'click'); handlers.push(callback); } };
const root = { dataset: {}, querySelector: selector => selector === 'iframe' ? frame : selector === '[data-vsl-play]' ? poster : null };
initSpecialVideo(null);
initSpecialVideo({ dataset: {}, querySelector: () => null });
let plays = 0;
initSpecialVideo(root, async () => ({ play() { plays++; } }));
initSpecialVideo(root);
await Promise.resolve();
assert.equal(poster.hidden, false);
assert.equal(frame.src, initial);
assert.equal(handlers.length, 1);
handlers[0]();
assert.equal(poster.hidden, true);
assert.equal(plays, 1);
assert.equal(new URL(frame.src).searchParams.get('autoplay'), 'false');
assert.equal(new URL(frame.src).pathname, new URL(initial).pathname);
assert.equal(new URL(frame.src).searchParams.get('muted'), 'false');
handlers[0]();
assert.equal(navigations, 0);
assert.equal(plays, 1);
const source = readFileSync(new URL('../src/lib/es2-special-video.mjs', import.meta.url), 'utf8');
assert.doesNotMatch(source, /mountMc2BunnyVideo|loadSource|\.m3u8|\.mp4|fetch\(/);
console.log('PASS: native Bunny iframe, same video, poster launch, autoplay, idempotence; no custom streaming engine.');
