import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { specialOffer } from '../src/data/es2-offre-speciale.mjs';
import { campaignState, bunnyEmbedUrl, clockParts, scheduledRemainingSeats } from '../src/lib/es2-special-offer.mjs';

const config = { ...specialOffer, published: true };
const start = Date.parse(config.startsAt), end = Date.parse(config.endsAt);
assert.equal((end - start) / 3600000, 54);
assert.equal(config.capacity, 5);
assert.equal(config.remainingSeats, 4);
assert.equal(campaignState(config, start - 1).phase, 'upcoming');
assert.equal(campaignState(config, start).phase, 'active');
assert.equal(campaignState(config, end - 1).phase, 'active');
assert.equal(campaignState(config, end).phase, 'expired');
assert.equal(campaignState(config, end + 1).available, false);
assert.equal(campaignState(specialOffer, start).phase, 'active');
assert.equal(campaignState({ ...specialOffer, published: false }, start).phase, 'draft');
assert.equal(campaignState({ ...config, remainingSeats: 0 }, start).phase, 'full');
for (const remainingSeats of [-1, config.capacity + 1, 1.5, '7']) assert.equal(campaignState({ ...config, remainingSeats }, start).phase, 'invalid');
assert.equal(campaignState({ ...config, endsAt: config.startsAt }, start).phase, 'invalid');
assert.equal(campaignState({ ...config, startsAt: 'bad-date' }, start).phase, 'invalid');
assert.equal(campaignState(config, NaN).phase, 'invalid');
const step = (end - start) / config.remainingSeats;
assert.equal(scheduledRemainingSeats(config, start - 1), 4);
assert.equal(scheduledRemainingSeats(config, start), 4);
assert.equal(scheduledRemainingSeats(config, start + step - 1), 4);
assert.equal(scheduledRemainingSeats(config, start + step), 3);
assert.equal(scheduledRemainingSeats(config, start + 2 * step), 2);
assert.equal(scheduledRemainingSeats(config, start + 3 * step), 1);
assert.equal(scheduledRemainingSeats(config, end - 1), 1);
assert.equal(scheduledRemainingSeats(config, end), 0);
assert.equal(campaignState(config, start + 2 * step).remaining, 2);
assert.equal(campaignState(config, start + 2 * step).phase, 'active');
assert.equal(campaignState(config, end).remaining, 0);
assert.deepEqual(clockParts((end - start) / 1000), ['02', '06', '00', '00']);
assert.deepEqual(clockParts(-1), ['00', '00', '00', '00']);
assert.match(bunnyEmbedUrl(config), /embed\/698588\/ec89b935-4508-47e5-9b58-b85c0c07db50/);
assert.match(bunnyEmbedUrl(config), /autoplay=false/);
assert.throws(() => bunnyEmbedUrl({ ...config, videoLibraryId: '../evil' }));
const page = readFileSync(new URL('../src/pages/es2-offre-speciale.astro', import.meta.url), 'utf8');
const offer = readFileSync(new URL('../src/components/mc2/DealOfferSpeciale.astro', import.meta.url), 'utf8');
const checkout = readFileSync(new URL('../src/lib/es2-special-checkout.mjs', import.meta.url), 'utf8');
assert.doesNotMatch(page + offer, /Mc2AccessGate|purchase-toast|mc2-offer-scarcity|startScarcity|CTA_APPEAR_SECONDS/);
assert.doesNotMatch(checkout, /fetch\(|sendBeacon|import .*spiffy|location.assign/);
assert.match(page, /const available = state.available/);
assert.match(page, /preview \? \{\} : \{ mountPayment: mountSpecialPayment \}/);
assert.match(page, /scheduledRemainingSeats\(config, seatNow\)/);
assert.match(page, /data-special-seat-count/);
assert.match(page, /const preview = local &&/);
for (const marker of ['6,47 €', '3,55 €', '197 €', '1 297 €', '<ProgramBenefits', '<MetamorphosisSteps', 'video-reviews-section']) assert.ok(offer.includes(marker), marker);
console.log('PASS: calendar boundaries, draft safety, linear seat schedule, media URL, price/content parity.');
